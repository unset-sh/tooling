// GitHub requires executable workflows in one flat directory. Authored category files are copied byte-for-byte
// after a provenance comment; this is a copier, not a YAML compiler. The --check path never writes.
// https://docs.github.com/en/actions/how-tos/reuse-automations/reuse-workflows (read 2026-11-22)
import { lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const categories = ["ci", "releases", "deployments", "pages", "automation", "code-scanning"];
const outputs = [".github/workflows", "workflow-templates"];
const filename = /^[A-Za-z0-9][A-Za-z0-9._-]*\.yml$/;
const header = (source) => `# Generated by scripts/workflows.mjs from ${source}; do not edit.\n`;

function statOrMissing(path) {
  try {
    return lstatSync(path);
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

/** Check each ancestor inside the root, so a link named `.github` cannot redirect generated output. */
function directory(root, relative) {
  let path = root;
  for (const part of ["", ...relative.split("/")]) {
    path = join(path, part);
    const stat = statOrMissing(path);
    if (stat === null) return false;
    if (stat.isSymbolicLink()) throw new Error(`${path}: symbolic links are not allowed`);
    if (!stat.isDirectory()) throw new Error(`${path}: expected a directory`);
  }
  return true;
}

/** Return all regular direct children; never follow a source or output link. */
function files(root, relative) {
  if (!directory(root, relative)) return new Map();
  const found = new Map();
  for (const name of readdirSync(join(root, relative)).sort()) {
    const path = `${relative}/${name}`;
    const stat = lstatSync(join(root, path));
    if (stat.isSymbolicLink()) throw new Error(`${path}: symbolic links are not allowed`);
    if (stat.isDirectory()) throw new Error(`${path}: nested directories are not supported`);
    if (!stat.isFile()) throw new Error(`${path}: expected a regular file`);
    found.set(name, readFileSync(join(root, path)));
  }
  return found;
}

function destination(source) {
  const [category, name] = source.split("/");
  if (!filename.test(name ?? "")) throw new Error(`${source}: unsafe workflow filename`);
  if (category === "templates") return `workflow-templates/${name}`;
  if (!categories.includes(category)) throw new Error(`${source}: unknown workflow category`);
  return `.github/workflows/${category}-${name}`;
}

function checkNames(names, source) {
  for (const name of names) {
    if (name.endsWith(".yaml")) throw new Error(`${source}/${name}: workflow filenames must end in .yml`);
    if (name.endsWith(".yml") && !filename.test(name)) throw new Error(`${source}/${name}: unsafe workflow filename`);
  }
}

function expectedFiles(root) {
  const expected = new Map();
  const addYaml = (source, bytes) => expected.set(destination(source), Buffer.concat([Buffer.from(header(source)), bytes]));
  for (const category of categories) {
    const sourceFiles = files(root, category);
    checkNames(sourceFiles.keys(), category);
    for (const [name, bytes] of sourceFiles) {
      if (name.endsWith(".yml")) addYaml(`${category}/${name}`, bytes);
    }
  }
  const templates = files(root, "templates");
  checkNames(templates.keys(), "templates");
  const displayNames = new Set();
  for (const [name, bytes] of templates) {
    if (name.endsWith(".properties.json")) {
      const yamlName = name.replace(/\.properties\.json$/, ".yml");
      if (!templates.has(yamlName)) throw new Error(`templates/${name}: metadata has no paired YAML workflow`);
    }
    if (!name.endsWith(".yml")) continue;
    const metadataName = name.replace(/\.yml$/, ".properties.json");
    const metadataBytes = templates.get(metadataName);
    if (!metadataBytes) throw new Error(`templates/${name}: missing metadata ${metadataName}`);
    let metadata;
    try {
      metadata = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(metadataBytes));
    } catch (error) {
      throw new Error(`templates/${metadataName}: invalid JSON metadata (${error.message})`);
    }
    for (const field of ["name", "description"]) {
      if (metadata === null || typeof metadata !== "object" || Array.isArray(metadata) ||
          typeof metadata[field] !== "string" || metadata[field].trim() === "") {
        throw new Error(`templates/${metadataName}: metadata needs a non-empty ${field}`);
      }
    }
    const displayName = metadata.name.trim().toLowerCase();
    if (displayNames.has(displayName)) throw new Error(`templates/${metadataName}: duplicate template name ${metadata.name}`);
    displayNames.add(displayName);
    addYaml(`templates/${name}`, bytes);
    expected.set(`workflow-templates/${metadataName}`, metadataBytes);
  }
  return expected;
}

/** Only the exact header in the correct destination grants ownership. */
function ownsYaml(path, bytes) {
  const firstLine = bytes.toString("utf8").split("\n", 1)[0];
  const match = /^# Generated by scripts\/workflows\.mjs from ([a-z-]+\/[A-Za-z0-9][A-Za-z0-9._-]*\.yml); do not edit\.$/.exec(firstLine);
  if (match === null) return false;
  if (destination(match[1]) !== path) throw new Error(`${path}: provenance names a different destination`);
  return true;
}

function outputFiles(root) {
  const existing = new Map();
  const owned = new Set();
  for (const output of outputs) {
    for (const [name, bytes] of files(root, output)) {
      const path = `${output}/${name}`;
      existing.set(path, bytes);
      if (name.endsWith(".yml") && ownsYaml(path, bytes)) owned.add(path);
    }
  }
  // JSON remains exactly the authored bytes. Its paired generated YAML establishes ownership.
  for (const path of owned) {
    if (!path.startsWith("workflow-templates/") || !path.endsWith(".yml")) continue;
    const metadata = path.replace(/\.yml$/, ".properties.json");
    if (existing.has(metadata)) owned.add(metadata);
  }
  return { existing, owned };
}

function validateOutputs(expected, existing, owned) {
  const folded = new Map();
  for (const path of [...expected.keys(), ...existing.keys()]) {
    const lower = path.toLowerCase();
    const previous = folded.get(lower);
    if (previous && previous !== path) throw new Error(`${path}: case-insensitive collision with ${previous}`);
    folded.set(lower, path);
  }
  for (const [path, bytes] of existing) {
    const desired = expected.get(path);
    const metadata = path.startsWith("workflow-templates/") && path.endsWith(".properties.json");
    // If YAML was removed accidentally, exact matching metadata can be retained while restoring it.
    const matchingMetadata = metadata && desired?.equals(bytes);
    if (desired && !owned.has(path) && !matchingMetadata) throw new Error(`${path}: refusing to overwrite an unmanaged file`);
    if (metadata && !owned.has(path) && !matchingMetadata && !existing.has(path.replace(/\.properties\.json$/, ".yml"))) {
      throw new Error(`${path}: standalone metadata has unknown ownership; inspect it manually`);
    }
  }
}

/** Return sorted paths that differ. Validate the entire operation before making any writes or removals. */
export function generate(root, { write = false } = {}) {
  root = resolve(root);
  if (!directory(root, "")) throw new Error(`${root}: repository directory does not exist`);
  const expected = expectedFiles(root);
  const { existing, owned } = outputFiles(root);
  validateOutputs(expected, existing, owned);
  const changed = [...expected].filter(([path, bytes]) => !existing.get(path)?.equals(bytes)).map(([path]) => path);
  for (const path of owned) if (!expected.has(path)) changed.push(path);
  changed.sort();
  if (write) {
    for (const path of changed) {
      if (expected.has(path)) {
        mkdirSync(dirname(join(root, path)), { recursive: true });
        writeFileSync(join(root, path), expected.get(path));
      } else {
        unlinkSync(join(root, path));
      }
    }
  }
  return changed;
}

function main(args) {
  if (args.length !== 1 && args.length !== 3) throw new Error("usage: node scripts/workflows.mjs --write|--check [--root <absolute-directory>]");
  const mode = args[0];
  if (!["--write", "--check"].includes(mode) || (args.length === 3 && (args[1] !== "--root" || !isAbsolute(args[2])))) {
    throw new Error("usage: node scripts/workflows.mjs --write|--check [--root <absolute-directory>]");
  }
  const root = args[2] ?? fileURLToPath(new URL("../", import.meta.url));
  const changes = generate(root, { write: mode === "--write" });
  if (mode === "--check" && changes.length) {
    throw new Error(`Generated workflow files are stale; run npm run workflows:\n${changes.join("\n")}`);
  }
  if (mode === "--write" && changes.length) console.log(changes.join("\n"));
}

function startedAsScript() {
  if (!process.argv[1] || process.argv[1] === "-") return false;
  return realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
}

if (startedAsScript()) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
