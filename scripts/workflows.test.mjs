test("unsafe manifest paths and duplicate or case-colliding mappings cannot overwrite files", (t) => {
  const records = [
    { source: "../outside.yml", output: ".github/workflows/check.yml" },
    { source: "workflows/shared/ci/check.yml", output: "../outside.yml" },
    { source: "workflows/shared/ci/check.yml", output: ".github/workflows/nested/check.yml" },
    { source: "workflows/shared/ci/check.yml", output: ".github/workflows/check.yaml" },
  ];
  for (const record of records) {
    const root = fixture(t);
    put(root, "workflows/manifest.json", JSON.stringify({ schemaVersion: 1, workflows: [record] }));
    const before = snapshot(root);
    assert.throws(() => generate(root, { write: true }), /manifest|mapping|path|filename/i);
    assert.deepEqual(snapshot(root), before);
  }
  for (const output of ["ci-check.yml", "CI-check.yml"]) {
    const root = fixture(t);
    source(root, "shared/ci/check.yml", "ci-check.yml");
    source(root, "web/ci/check.yml", output);
    assert.throws(() => generate(root, { write: true }), /collision|duplicate/i);
  }
  const root = fixture(t);
  source(root, "shared/ci/check.yml", "one.yml");
  source(root, "shared/ci/check.yml", "two.yml");
  assert.throws(() => generate(root, { write: true }), /collision|duplicate/i);
});

test("manifest files and workflow namespace ancestors cannot be symbolic links", (t) => {
  for (const relative of ["workflows/manifest.json", "workflows/shared", "workflows/shared/ci", "workflows"]) {
    const root = fixture(t);
    source(root, "shared/ci/check.yml", "ci-check.yml");
    const target = join(root, "outside");
    mkdirSync(target);
    rmSync(join(root, relative), { recursive: true });
    symlinkSync(target, join(root, relative));
    assert.throws(() => generate(root, { write: true }), /symbolic|symlink/i);
  }
});

test("hard-linked output cannot redirect a generated write into another file", (t) => {
  const root = fixture(t);
  source(root, "shared/ci/check.yml", "ci-check.yml");
  put(root, "outside.yml", checkOutput + "# preserve this\n");
  mkdirSync(join(root, ".github/workflows"), { recursive: true });
  linkSync(join(root, "outside.yml"), join(root, ".github/workflows/ci-check.yml"));
  const before = readFileSync(join(root, "outside.yml"));
  assert.throws(() => generate(root, { write: true }), /regular|link/i);
  assert.deepEqual(readFileSync(join(root, "outside.yml")), before);
});

