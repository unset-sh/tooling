import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";
import { generate } from "./workflows.mjs";

const cli = fileURLToPath(new URL("./workflows.mjs", import.meta.url));
const yaml = "name: Check\non:\n  workflow_call:\npermissions: {}\n";
const properties = '{"name":"Check","description":"Check a repository"}\n';
const checkOutput = "# Generated by scripts/workflows.mjs from ci/check.yml; do not edit.\n" + yaml;
const templateOutput = "# Generated by scripts/workflows.mjs from templates/check.yml; do not edit.\n" + yaml;

function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "workflow-generation-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return root;
}

function put(root, path, data) {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), data);
}

function snapshot(root, path = "") {
  return readdirSync(join(root, path)).sort().flatMap((name) => {
    const relative = path ? `${path}/${name}` : name;
    const stat = lstatSync(join(root, relative));
    if (stat.isDirectory()) return [[relative, "directory"], ...snapshot(root, relative)];
    return [[relative, stat.isSymbolicLink() ? "link" : readFileSync(join(root, relative), "utf8")]];
  });
}

test("check reports missing outputs without creating directories", (t) => {
  const root = fixture(t);
  put(root, "ci/check.yml", yaml);
  const before = snapshot(root);
  assert.deepEqual(generate(root, { write: false }), [".github/workflows/ci-check.yml"]);
  assert.deepEqual(snapshot(root), before);
});

test("write copies source bytes with provenance and is idempotent", (t) => {
  const root = fixture(t);
  put(root, "ci/check.yml", yaml);
  assert.deepEqual(generate(root, { write: true }), [".github/workflows/ci-check.yml"]);
  assert.equal(readFileSync(join(root, ".github/workflows/ci-check.yml"), "utf8"), checkOutput);
  assert.deepEqual(generate(root, { write: true }), []);
  assert.deepEqual(generate(root, { write: false }), []);
});

test("generation sorts paths independently of source creation order", (t) => {
  const root = fixture(t);
  put(root, "releases/package.yml", yaml);
  put(root, "ci/z.yml", yaml);
  put(root, "ci/a.yml", yaml);
  assert.deepEqual(generate(root, { write: true }), [
    ".github/workflows/ci-a.yml", ".github/workflows/ci-z.yml", ".github/workflows/releases-package.yml",
  ]);
});

test("check detects a hand edit without repairing it", (t) => {
  const root = fixture(t);
  put(root, "ci/check.yml", yaml);
  put(root, ".github/workflows/ci-check.yml", checkOutput + "# hand edit\n");
  const before = snapshot(root);
  assert.deepEqual(generate(root, { write: false }), [".github/workflows/ci-check.yml"]);
  assert.deepEqual(snapshot(root), before);
  generate(root, { write: true });
  assert.equal(readFileSync(join(root, ".github/workflows/ci-check.yml"), "utf8"), checkOutput);
});

test("a removed source is reported and write removes only its owned output", (t) => {
  const root = fixture(t);
  put(root, ".github/workflows/ci-check.yml", checkOutput);
  put(root, ".github/workflows/manual.yml", yaml);
  assert.deepEqual(generate(root, { write: false }), [".github/workflows/ci-check.yml"]);
  assert.ok(existsSync(join(root, ".github/workflows/ci-check.yml")));
  generate(root, { write: true });
  assert.ok(!existsSync(join(root, ".github/workflows/ci-check.yml")));
  assert.equal(readFileSync(join(root, ".github/workflows/manual.yml"), "utf8"), yaml);
});

test("an unmanaged collision is refused before any output is written", (t) => {
  const root = fixture(t);
  put(root, "ci/a.yml", yaml);
  put(root, "ci/check.yml", yaml);
  put(root, ".github/workflows/ci-check.yml", yaml);
  const before = snapshot(root);
  assert.throws(() => generate(root, { write: true }), /unmanaged/i);
  assert.deepEqual(snapshot(root), before);
});

test("a similar provenance comment never grants ownership", (t) => {
  const root = fixture(t);
  put(root, "ci/check.yml", yaml);
  put(root, ".github/workflows/ci-check.yml", "# Generated by another tool from ci/check.yml\n" + yaml);
  assert.throws(() => generate(root, { write: true }), /unmanaged/i);
});

test("a provenance header for a different destination is refused", (t) => {
  const root = fixture(t);
  put(root, ".github/workflows/ci-other.yml", checkOutput);
  assert.throws(() => generate(root, { write: true }), /provenance|destination/i);
  assert.ok(existsSync(join(root, ".github/workflows/ci-other.yml")));
});

test("case-insensitive generated path collisions are refused", (t) => {
  const root = fixture(t);
  // Distinct source categories can collide through a hyphen in the basename.
  put(root, "code-scanning/check.yml", yaml);
  put(root, "ci/code.yml", yaml);
  put(root, ".github/workflows/CI-code.yml", yaml);
  assert.throws(() => generate(root, { write: true }), /case|collision/i);
  assert.ok(!existsSync(join(root, ".github/workflows/code-scanning-check.yml")));
});

test("nested sources fail instead of silently dropping a workflow", (t) => {
  const root = fixture(t);
  put(root, "ci/node/check.yml", yaml);
  assert.throws(() => generate(root, { write: true }), /nested|directory/i);
});

test("unsafe source filenames fail before writing", (t) => {
  const root = fixture(t);
  put(root, "ci/bad name.yml", yaml);
  assert.throws(() => generate(root, { write: true }), /name/i);
});

test("all source symlinks are refused", (t) => {
  const root = fixture(t);
  put(root, "outside.yml", yaml);
  mkdirSync(join(root, "ci"));
  symlinkSync(join(root, "outside.yml"), join(root, "ci/check.yml"));
  assert.throws(() => generate(root, { write: true }), /symbolic|symlink/i);
  rmSync(join(root, "ci"), { recursive: true });
  mkdirSync(join(root, "elsewhere"));
  symlinkSync(join(root, "elsewhere"), join(root, "ci"));
  assert.throws(() => generate(root, { write: true }), /symbolic|symlink/i);
});

test("output ancestor, directory and file symlinks are refused", (t) => {
  for (const relative of [".github", ".github/workflows", ".github/workflows/ci-check.yml"]) {
    const root = fixture(t);
    put(root, "ci/check.yml", yaml);
    put(root, "outside/keep.yml", "untouched\n");
    mkdirSync(dirname(join(root, relative)), { recursive: true });
    symlinkSync(join(root, "outside"), join(root, relative));
    assert.throws(() => generate(root, { write: true }), /symbolic|symlink/i, relative);
    assert.equal(readFileSync(join(root, "outside/keep.yml"), "utf8"), "untouched\n");
  }
});

test("template YAML and metadata are emitted as a pair with exact JSON bytes", (t) => {
  const root = fixture(t);
  put(root, "templates/check.yml", yaml);
  put(root, "templates/check.properties.json", properties);
  assert.deepEqual(generate(root, { write: true }), ["workflow-templates/check.properties.json", "workflow-templates/check.yml"]);
  assert.equal(readFileSync(join(root, "workflow-templates/check.yml"), "utf8"), templateOutput);
  assert.equal(readFileSync(join(root, "workflow-templates/check.properties.json"), "utf8"), properties);
  assert.deepEqual(generate(root, { write: false }), []);
});

test("missing template pair members and malformed metadata fail without partial output", (t) => {
  for (const data of [undefined, "{", "[]", '{"name":"Check"}', '{"name":"","description":"Check"}']) {
    const root = fixture(t);
    put(root, "ci/check.yml", yaml);
    put(root, "templates/check.yml", yaml);
    if (data !== undefined) put(root, "templates/check.properties.json", data);
    const before = snapshot(root);
    assert.throws(() => generate(root, { write: true }), /metadata|JSON|description|name/i);
    assert.deepEqual(snapshot(root), before);
  }
  const root = fixture(t);
  put(root, "templates/check.properties.json", properties);
  assert.throws(() => generate(root, { write: true }), /pair|YAML|workflow/i);
});

test("duplicate template display names are refused", (t) => {
  const root = fixture(t);
  for (const name of ["one", "two"]) {
    put(root, `templates/${name}.yml`, yaml);
    put(root, `templates/${name}.properties.json`, properties);
  }
  assert.throws(() => generate(root, { write: true }), /duplicate|name/i);
});

test("orphaned generated template YAML and its metadata are removed together", (t) => {
  const root = fixture(t);
  put(root, "workflow-templates/check.yml", templateOutput);
  put(root, "workflow-templates/check.properties.json", properties);
  assert.deepEqual(generate(root, { write: false }), ["workflow-templates/check.properties.json", "workflow-templates/check.yml"]);
  generate(root, { write: true });
  assert.ok(!existsSync(join(root, "workflow-templates/check.yml")));
  assert.ok(!existsSync(join(root, "workflow-templates/check.properties.json")));
});

test("a missing generated template YAML can be restored beside matching metadata", (t) => {
  const root = fixture(t);
  put(root, "templates/check.yml", yaml);
  put(root, "templates/check.properties.json", properties);
  put(root, "workflow-templates/check.properties.json", properties);
  assert.deepEqual(generate(root, { write: true }), ["workflow-templates/check.yml"]);
  assert.equal(readFileSync(join(root, "workflow-templates/check.yml"), "utf8"), templateOutput);
});

test("ambiguous standalone metadata is preserved for manual inspection", (t) => {
  for (const sourcePresent of [true, false]) {
    const root = fixture(t);
    if (sourcePresent) {
      put(root, "templates/check.yml", yaml);
      put(root, "templates/check.properties.json", properties);
    }
    put(root, "workflow-templates/check.properties.json", '{"name":"Unrelated","description":"Keep this"}\n');
    const before = snapshot(root);
    assert.throws(() => generate(root, { write: true }), /metadata|unmanaged|manual/i);
    assert.deepEqual(snapshot(root), before);
  }
});

test("CLI check fails for drift, write repairs it, and bad arguments fail", (t) => {
  const root = fixture(t);
  put(root, "ci/check.yml", yaml);
  const run = (...args) => spawnSync(process.execPath, [cli, ...args, "--root", root], { encoding: "utf8" });
  const missing = run("--check");
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /ci-check\.yml/);
  const write = run("--write");
  assert.equal(write.status, 0, write.stderr);
  assert.equal(run("--check").status, 0);
  assert.equal(run("--write", "--check").status, 1);
  assert.equal(run("--unknown").status, 1);
});

test("the API imports from stdin without trying to run its CLI", () => {
  const imported = spawnSync(process.execPath, ["--input-type=module", "-"], {
    input: `const { generate } = await import(${JSON.stringify(new URL("./workflows.mjs", import.meta.url).href)}); console.log(typeof generate);`,
    encoding: "utf8",
  });
  assert.equal(imported.status, 0, imported.stderr);
  assert.equal(imported.stdout, "function\n");
});
