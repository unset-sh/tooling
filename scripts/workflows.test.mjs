test("CLI check fails for drift, write repairs it, and bad arguments fail", (t) => {
  const root = fixture(t);
  source(root, "shared/ci/check.yml", "ci-check.yml");
  const run = (...args) => spawnSync(process.execPath, [cli, ...args, "--root", root], { encoding: "utf8" });
  const missing = run("--check");
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /ci-check\.yml/);
  const write = run("--write");
  assert.equal(write.status, 0, write.stderr);
  assert.equal(run("--check").status, 0);
  assert.equal(run("--write", "--check").status, 1);
  assert.equal(run("--unknown").status, 1);
});

