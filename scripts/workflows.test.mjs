test("the six previous generated headers migrate only at their original destinations", (t) => {
  const pairs = [
    ["ci/check.yml", "shared/ci/check.yml", "ci-check.yml"],
    ["ci/self.yml", "tooling/ci/self.yml", "ci-self.yml"],
    ["automation/docs-export.yml", "shared/docs/export.yml", "automation-docs-export.yml"],
    ["automation/docs-self.yml", "tooling/docs/self.yml", "automation-docs-self.yml"],
    ["releases/package.yml", "shared/releases/package.yml", "releases-package.yml"],
    ["releases/self.yml", "tooling/release/self.yml", "releases-self.yml"],
  ];
  const root = fixture(t);
  for (const [old, current, output] of pairs) {
    source(root, current, output);
    put(root, `.github/workflows/${output}`, `# Generated by scripts/workflows.mjs from ${old}; do not edit.\n${yaml}`);
  }
  assert.equal(generate(root, { write: true }).length, 6);
  assert.deepEqual(generate(root), []);
  const other = fixture(t);
  source(other, "shared/ci/unknown.yml", "ci-unknown.yml");
  put(other, ".github/workflows/ci-unknown.yml", `# Generated by scripts/workflows.mjs from ci/unknown.yml; do not edit.\n${yaml}`);
  assert.throws(() => generate(other, { write: true }), /unmanaged/);
  put(other, ".github/workflows/ci-unknown.yml", `# Generated by scripts/workflows.mjs from ci/check.yml; do not edit.\n${yaml}`);
  assert.throws(() => generate(other, { write: true }), /destination/);
});

